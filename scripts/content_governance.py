#!/usr/bin/env python3
"""Catalog rendering and read-only content checks. Python 3.9+, standard library only."""
import argparse
import hashlib
import html
import json
import os
from pathlib import Path
import re
import sys
from urllib.parse import unquote, urlsplit
import zlib

ROOT = Path(__file__).resolve().parents[1]
CATEGORIES = {
    "cpp": ("C++ 基础库", "notes/README.md"),
    "base": ("基础框架与源码实践", "notes/base-lib/README.md"),
    "business": ("业务链路与契约", "notes/business-lib/README.md"),
    "ai-tools": ("AI 工具", "ai-tools/README.md"),
    "planning": ("历史选题与计划", "notes/weekly-topic-selection/README.md"),
}
NAV = re.compile(r"\n<!-- topic-nav:start -->.*?<!-- topic-nav:end -->\n", re.S)


def read_json(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def note_paths():
    return {p.relative_to(ROOT).as_posix()
            for folder in ("notes", "ai-tools")
            for p in (ROOT / folder).rglob("*.md") if p.name != "README.md"}


def outside_fences(text):
    """Blank fenced code (including Markdown examples), preserving line numbers."""
    result, fence = [], None
    for line in text.splitlines():
        # Nested list items may indent fences by four or more spaces.
        match = re.match(r"^\s*(`{3,}|~{3,})", line)
        if match:
            marker = match[1]
            if fence is None:
                fence = marker
            elif marker[0] == fence[0] and len(marker) >= len(fence):
                fence = None
            result.append("")
        else:
            result.append(line if fence is None else "")
    return "\n".join(result)


def rel_link(source, target):
    return Path(os.path.relpath(ROOT / target, (ROOT / source).parent)).as_posix()


def label(text):
    return html.escape(text.replace("[", "［").replace("]", "］").replace("\n", " "))


def validate_catalog(topics):
    errors, ids, paths = [], set(), set()
    for topic in topics:
        tid = topic["id"]
        if tid in ids:
            errors.append(f"重复 topic_id: {tid}")
        ids.add(tid)
        if topic["category"] not in CATEGORIES:
            errors.append(f"未知分类: {tid}")
        primary = []
        for doc in topic["documents"]:
            path = doc["path"]
            if path in paths:
                errors.append(f"文章重复登记: {path}")
            paths.add(path)
            if path.startswith("/") or ".." in Path(path).parts:
                errors.append(f"无效文章路径: {path}")
            if doc["role"] == "primary":
                primary.append(path)
            elif doc["role"] != "supplement":
                errors.append(f"未知阅读角色: {path}")
            elif not doc.get("scope", "").strip():
                errors.append(f"补充文章缺少阅读范围: {path}")
        if primary != [topic["canonical"]]:
            errors.append(f"必须恰有一篇主文并与 canonical 一致: {tid}")
    for path in sorted(note_paths() - paths):
        errors.append(f"文章尚未登记主题（先查重再加入 catalog.json）: {path}")
    for path in sorted(paths - note_paths()):
        errors.append(f"登记的文章不存在: {path}")
    return errors


def generated_files(topics):
    output = {}
    summary = ["<!-- catalog-summary:start -->", "",
               f"按主题阅读 C++ 基础库、框架机制、业务链路和 AI 工具。现有 **{sum(len(t['documents']) for t in topics)} 篇资料，{len(topics)} 个主题入口**；同题历史版本和独立场景折叠在各主题的补充阅读中。",
               "", "## 阅读目录", "", "| 分类 | 主题数 | 资料数 | 入口 |", "|---|---:|---:|---|"]
    for category, (title, index) in CATEGORIES.items():
        selected = [t for t in topics if t["category"] == category]
        summary.append(f"| {title} | {len(selected)} | {sum(len(t['documents']) for t in selected)} | [主题目录]({index}) |")
    summary += ["", "<!-- catalog-summary:end -->"]
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    pattern = r"<!-- catalog-summary:start -->.*?<!-- catalog-summary:end -->"
    if not re.search(pattern, readme, re.S):
        raise ValueError("README.md 缺少目录生成标记")
    output["README.md"] = re.sub(pattern, "\n".join(summary), readme, flags=re.S)
    for category, (title, path) in CATEGORIES.items():
        selected = [t for t in topics if t["category"] == category]
        count = sum(len(t["documents"]) for t in selected)
        lines = [f"# {title}", "", "<!-- Generated by scripts/content_governance.py render; edit governance/catalog.json. -->", "",
                 f"[返回首页]({rel_link(path, 'README.md')}) · {len(selected)} 个主题 / {count} 篇资料。", "",
                 "每个主题先读主文；同题版本折叠在补充资料中。主文是阅读入口，不代表最新源码已经复核。", ""]
        for topic in selected:
            lines += [f"## {label(topic['title'])}", "", f"主题标识：`{topic['id']}`", "",
                      f"[阅读主文]({rel_link(path, topic['canonical'])})", ""]
            supplements = [d for d in topic["documents"] if d["role"] == "supplement"]
            if supplements:
                lines += ["<details>", f"<summary>同题补充与历史版本（{len(supplements)} 篇）</summary>", ""]
                for doc in supplements:
                    lines += [f"- [{label(doc['title'])}]({rel_link(path, doc['path'])})：{label(doc['scope'])}"]
                lines += ["", "</details>", ""]
        output[path] = "\n".join(lines).rstrip() + "\n"
    for topic in topics:
        if len(topic["documents"]) < 2:
            continue
        for doc in topic["documents"]:
            path = doc["path"]
            text = NAV.sub("", (ROOT / path).read_text(encoding="utf-8"))
            first = text.index("\n") if "\n" in text else len(text)
            index = CATEGORIES[topic["category"]][1]
            role = "主文" if doc["role"] == "primary" else "同题补充 / 历史版本"
            nav = (f"\n<!-- topic-nav:start -->\n> 主题：`{topic['id']}` · {role} · "
                   f"[主题目录]({rel_link(path, index)})")
            if doc["role"] != "primary":
                nav += f" · [先读主文]({rel_link(path, topic['canonical'])})"
            nav += "\n<!-- topic-nav:end -->\n"
            output[path] = text[:first] + nav + text[first:]
    return output


def local_link_issues():
    """Check relative Markdown links and HTML href/src outside examples.

    Source-code absolute paths, web URLs and historical fragment anchors are
    outside this check. Reference-style Markdown links are resolved too.
    """
    issues = set()
    for path in sorted(ROOT.rglob("*.md")):
        if ".git" in path.parts:
            continue
        text = outside_fences(path.read_text(encoding="utf-8"))
        # Inline code may contain sample links and must not be interpreted.
        text = re.sub(r"(`+).*?\1", "", text)
        targets = re.findall(r"!?\[[^\]\n]*\]\(\s*(<[^>]+>|[^\s)]+)", text)
        targets += re.findall(r"^\s{0,3}\[[^\]]+\]:\s*(<[^>]+>|\S+)", text, re.M)
        targets += re.findall(r'(?:href|src)=[\"\x27]([^\"\x27]+)', text)
        for target in targets:
            target = html.unescape(target.strip("<>"))
            parsed = urlsplit(target)
            if parsed.scheme or parsed.netloc or not parsed.path or target.startswith("/"):
                continue
            dest = (path.parent / unquote(parsed.path)).resolve()
            if not dest.exists():
                issues.add(f"{path.relative_to(ROOT).as_posix()} -> {target}")
    return issues


def comparable_text(text):
    text = NAV.sub("", text)
    text = re.sub(r"<style\b.*?</style>", "", text, flags=re.S | re.I)
    text = re.sub(r"<[^>]+>", "", text)
    text = re.sub(r"https?://\S+", "", text)
    text = re.sub(r"\d{4}-?\d{2}-?\d{2}", "", text)
    return re.sub(r"\s+", "", text).lower()


def fingerprints(text):
    # Content-based sampling, unlike stride sampling, tolerates prefix edits.
    normalized = comparable_text(text)
    grams = (normalized[i:i + 12] for i in range(max(0, len(normalized) - 11)))
    hashes = (zlib.crc32(g.encode()) for g in grams)
    return {h for h in hashes if h % 16 == 0}


def similar_pairs(paths, threshold=0.80):
    features = {p: fingerprints((ROOT / p).read_text(encoding="utf-8")) for p in sorted(paths)}
    pairs = []
    names = list(features)
    for i, left in enumerate(names):
        for right in names[i + 1:]:
            a, b = features[left], features[right]
            # Avoid treating very short notices as substantive duplicates.
            if min(len(a), len(b)) < 40:
                continue
            score = len(a & b) / min(len(a), len(b))
            if score >= threshold:
                pairs.append((score, left, right))
    return sorted(pairs, reverse=True)


def check(topics):
    errors = validate_catalog(topics)
    if errors:
        return errors
    for path, expected in generated_files(topics).items():
        if not (ROOT / path).exists() or (ROOT / path).read_text(encoding="utf-8") != expected:
            errors.append(f"目录或主题导航未同步，请执行 render: {path}")
    baseline = read_json("governance/link-baseline.json")
    existing = {item["issue"] for item in baseline["issues"]}
    current = local_link_issues()
    errors += [f"新增失效链接: {issue}" for issue in sorted(current - existing)]
    errors += [f"链接已修复，请删除过时豁免: {issue}" for issue in sorted(existing - current)]
    seen = {}
    for path in sorted(note_paths()):
        raw = (ROOT / path).read_text(encoding="utf-8")
        digest = hashlib.sha256(comparable_text(raw).encode()).hexdigest()
        if digest in seen:
            errors.append(f"重复全文（忽略日期与导航）: {seen[digest]} / {path}")
        seen[digest] = path
    reviewed = read_json("governance/similarity-reviewed.json")["pairs"]
    accepted = {tuple(sorted(item["paths"])) for item in reviewed if item.get("reason")}
    for score, a, b in similar_pairs(note_paths()):
        if tuple(sorted((a, b))) not in accepted:
            errors.append(f"高相似正文需合并或说明保留理由（{score:.0%}）: {a} / {b}")
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    for command in ("render", "check", "audit"):
        sub.add_parser(command)
    candidate = sub.add_parser("candidate", help="写作前按主题或草稿查重；仅报告，不修改文件")
    candidate.add_argument("--topic", required=True)
    candidate.add_argument("--file", type=Path)
    candidate.add_argument("--plan", type=Path)
    candidate.add_argument("--date", help="与 --plan 同用，要求提供当日 YYYY-MM-DD，禁止自动回退旧计划")
    args = parser.parse_args()
    topics = read_json("governance/catalog.json")["topics"]
    if args.command == "render":
        errors = validate_catalog(topics)
        if errors:
            print("\n".join(errors), file=sys.stderr)
            return 1
        output = generated_files(topics)
        for path, text in output.items():
            (ROOT / path).write_text(text, encoding="utf-8")
        print(f"已同步 {len(CATEGORIES)} 份目录与同题导航；{len(topics)} 个主题。")
    elif args.command == "check":
        errors = check(topics)
        if errors:
            print("\n".join(errors), file=sys.stderr)
            return 1
        print(f"PASS: {len(note_paths())} 篇资料，{len(topics)} 个主题；目录、登记、重复正文、相对文件链接检查通过。")
    elif args.command == "audit":
        duplicate_topics = [t for t in topics if len(t["documents"]) > 1]
        print(json.dumps({"articles": len(note_paths()), "topics": len(topics),
                          "multi_article_topics": len(duplicate_topics),
                          "similar_pairs": similar_pairs(note_paths(), 0.55),
                          "broken_local_links": sorted(local_link_issues())}, ensure_ascii=False, indent=2))
    else:
        if args.plan:
            plan = json.loads(args.plan.read_text(encoding="utf-8"))
            if not args.date or plan.get("date") != args.date:
                print("拒绝复用旧计划：计划必须包含与 --date 一致的 date。请先重新选题。", file=sys.stderr)
                return 1
        matches = [t for t in topics if args.topic.lower() in (t["id"] + " " + t["title"]).lower()]
        for topic in matches:
            print(f"已有主题 {topic['id']} -> {topic['canonical']}；优先更新主文。")
        if not matches:
            print("未找到同名主题；仍需检查近义词和草稿正文，不能据此证明无重复。")
        if args.file:
            a = fingerprints(args.file.read_text(encoding="utf-8"))
            scores = []
            for path in sorted(note_paths()):
                if (ROOT / path).resolve() == args.file.resolve():
                    continue
                b = fingerprints((ROOT / path).read_text(encoding="utf-8"))
                score = len(a & b) / max(1, min(len(a), len(b)))
                scores.append((score, path))
            for score, path in sorted(scores, reverse=True)[:5]:
                print(f"正文重合候选 {score:.0%}: {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
